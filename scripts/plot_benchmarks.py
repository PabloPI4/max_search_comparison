#!/usr/bin/env python3
import argparse
import json
import re
import os
import pandas as pd
import matplotlib.pyplot as plt

def parse_benchmark_name(name):
    """Extracts data type, size (N), and metric type (mean/stddev)."""
    pattern = r"benchmark_max_search_atomic<(.+)>/(\d+).*_(mean|stddev)$"
    match = re.search(pattern, str(name))
    if match:
        dtype = match.group(1).strip()
        size = int(match.group(2))
        stat_type = match.group(3)
        return dtype, size, stat_type
    return None, None, None

def plot_benchmarks(input_json, output_dir):
    if not os.path.exists(input_json) or os.path.getsize(input_json) == 0:
        print(f"Error: File {input_json} is empty or does not exist.")
        return

    os.makedirs(output_dir, exist_ok=True)
    
    with open(input_json, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if "benchmarks" not in data:
        print("Error: Key 'benchmarks' not found in JSON file.")
        return

    df = pd.DataFrame(data["benchmarks"])

    parsed_data = df['name'].apply(parse_benchmark_name)
    df['dtype'] = [p[0] for p in parsed_data]
    df['size'] = [p[1] for p in parsed_data]
    df['stat_type'] = [p[2] for p in parsed_data]
    
    df = df.dropna(subset=['dtype'])
    
    if df.empty:
        print("Warning: No '_mean' or '_stddev' entries found in data.")
        return

    df['bytes_per_second'] = pd.to_numeric(df['bytes_per_second'], errors='coerce')
    
    df['gb_per_sec'] = df['bytes_per_second'] / 1e9
    
    dtypes = df['dtype'].unique()
    
    for dtype in dtypes:
        df_type = df[df['dtype'] == dtype]
        
        means = df_type[df_type['stat_type'] == 'mean'].sort_values('size')
        stddevs = df_type[df_type['stat_type'] == 'stddev'].sort_values('size')
        
        if means.empty:
            continue
            
        x_sizes = means['size']
        y_mean = means['gb_per_sec'].values
        y_std = stddevs['gb_per_sec'].values if not stddevs.empty else [0] * len(y_mean)
        
        y_upper = y_mean + y_std
        y_lower = y_mean - y_std
        
        plt.figure(figsize=(9, 6))
        
        plt.plot(x_sizes, y_mean, marker='o', linewidth=2, color='#1f77b4', label='Mean atomicMax (GB/s)')
        
        plt.fill_between(x_sizes, y_lower, y_upper, color='#1f77b4', alpha=0.25, label='Std atomicMax (±σ)')
        
        plt.xscale('log')
        plt.xlabel('Number of elements ($N$)', fontsize=12)
        plt.ylabel('Effective bandwidth (GB/s)', fontsize=12)
        plt.title(f'Data type: {dtype}', fontsize=14, fontweight='bold')
        plt.grid(True, which="both", linestyle="--", alpha=0.5)
        plt.legend(loc='upper left', fontsize=11)
        
        plt.tight_layout()
        
        # Save plot as PNG
        safe_dtype_name = dtype.replace(' ', '_')
        output_path = os.path.join(output_dir, f'benchmark_{safe_dtype_name}.png')
        plt.savefig(output_path, dpi=300)
        plt.close()
        
        print(f" -> Plot stored: {output_path}")

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description='Process Google Benchmark JSON results and generate GB/s plot graphics.')
    parser.add_argument('--input', required=True, help='Path to input JSON file generated by Google Benchmark')
    parser.add_argument('--output-dir', default='./plots', help='Directory to store output PNG plots')
    args = parser.parse_args()
    
    plot_benchmarks(args.input, args.output_dir)